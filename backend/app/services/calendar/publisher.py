import json
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol
from urllib.parse import urlencode
from urllib.request import Request, urlopen

from backend.app.services.calendar.https import google_ssl_context


class CalendarPublishError(ValueError):
    """Raised when an approved schedule cannot be published."""


@dataclass(frozen=True, slots=True)
class CalendarCalledActor:
    character_name: str
    actor_name: str
    email: str


@dataclass(frozen=True, slots=True)
class CalendarSession:
    id: int
    scene_code: str
    start: datetime
    end: datetime
    called: tuple[CalendarCalledActor, ...]


@dataclass(frozen=True, slots=True)
class CalendarEventPreview:
    session_id: int
    title: str
    description: str
    start: datetime
    end: datetime
    attendee_emails: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class PublishedEvent:
    session_id: int
    event_id: str
    status: str


@dataclass(frozen=True, slots=True)
class PublishReport:
    published_count: int
    failed_count: int
    events: tuple[PublishedEvent, ...]


class CalendarPublisher(Protocol):
    def publish(self, sessions: tuple[CalendarSession, ...]) -> PublishReport: ...


class GoogleCalendarTransport(Protocol):
    def create_event(
        self,
        *,
        calendar_id: str,
        access_token: str,
        event: dict[str, object],
    ) -> str: ...


class GoogleCalendarHTTPTransport:
    def create_event(
        self,
        *,
        calendar_id: str,
        access_token: str,
        event: dict[str, object],
    ) -> str:
        url = f"https://www.googleapis.com/calendar/v3/calendars/{calendar_id}/events"
        request = Request(
            url,
            data=json.dumps(event).encode(),
            headers={
                "Authorization": f"Bearer {access_token}",
                "Content-Type": "application/json",
            },
            method="POST",
        )
        with urlopen(request, timeout=15, context=google_ssl_context()) as response:  # noqa: S310
            payload = json.loads(response.read())
        event_id = payload.get("id")
        if not isinstance(event_id, str):
            raise CalendarPublishError("Google Calendar response did not contain an event id")
        return event_id


class FakeCalendarPublisher:
    def publish(self, sessions: tuple[CalendarSession, ...]) -> PublishReport:
        events = tuple(
            PublishedEvent(session.id, f"fake-event-{session.id}", "PUBLISHED")
            for session in sessions
        )
        return PublishReport(len(events), 0, events)


class GoogleCalendarPublisher:
    def __init__(
        self,
        *,
        access_token: str,
        calendar_id: str = "primary",
        transport: GoogleCalendarTransport | None = None,
    ) -> None:
        if not access_token:
            raise CalendarPublishError("Google access token is required")
        self._access_token = access_token
        self._calendar_id = calendar_id
        self._transport = transport or GoogleCalendarHTTPTransport()

    def publish(self, sessions: tuple[CalendarSession, ...]) -> PublishReport:
        published: list[PublishedEvent] = []
        failed = 0
        for preview in build_event_previews(sessions):
            try:
                event_id = self._transport.create_event(
                    calendar_id=self._calendar_id,
                    access_token=self._access_token,
                    event=_google_event_payload(preview),
                )
                published.append(PublishedEvent(preview.session_id, event_id, "PUBLISHED"))
            except (OSError, ValueError):
                failed += 1
                published.append(PublishedEvent(preview.session_id, "", "FAILED"))
        return PublishReport(len(published) - failed, failed, tuple(published))


def build_event_previews(
    sessions: tuple[CalendarSession, ...],
) -> tuple[CalendarEventPreview, ...]:
    previews: list[CalendarEventPreview] = []
    for session in sorted(sessions, key=lambda item: (item.start, item.id)):
        called_lines = [
            f"{item.character_name.upper()} // {item.actor_name.upper()}" for item in session.called
        ]
        description = (
            f"SCENE: {session.scene_code}\n\nCALLED:\n"
            + ("\n".join(called_lines) if called_lines else "NO ACTORS CALLED")
            + "\n\nGENERATED BY STAGE SCHEDULER"
        )
        previews.append(
            CalendarEventPreview(
                session.id,
                f"REHEARSAL // {session.scene_code}",
                description,
                session.start,
                session.end,
                tuple(sorted({item.email for item in session.called if item.email})),
            )
        )
    return tuple(previews)


def build_google_auth_url(client_id: str, redirect_uri: str, state: str) -> str:
    if not client_id or not redirect_uri or not state:
        raise CalendarPublishError("Google OAuth client id, redirect URI, and state are required")
    query = urlencode(
        {
            "client_id": client_id,
            "redirect_uri": redirect_uri,
            "response_type": "code",
            "scope": "https://www.googleapis.com/auth/calendar.freebusy",
            "access_type": "offline",
            "include_granted_scopes": "true",
            "prompt": "consent",
            "state": state,
        }
    )
    return f"https://accounts.google.com/o/oauth2/v2/auth?{query}"


def _google_event_payload(preview: CalendarEventPreview) -> dict[str, object]:
    return {
        "summary": preview.title,
        "description": preview.description,
        "start": {"dateTime": preview.start.isoformat()},
        "end": {"dateTime": preview.end.isoformat()},
        "attendees": [{"email": email} for email in preview.attendee_emails],
    }
